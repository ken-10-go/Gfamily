/**
 * 縦書きに合わせて文字を置き換える。
 *
 * 生没年の「1931–2025」の横棒は、縦書きだと横に寝たままで、
 * 線が途切れたように見える。縦の棒に置き換える。
 *
 * ⚠ 置き換え先に `｜`（全角の縦線）を使ってはいけない。
 * 記号の類はフォントが**縦書き用の字形**に差し替えるので、縦線の記号はかえって
 * 横線になる（実機で確かめた）。漢字は差し替えの対象外なので、
 * 縦棒の字である `丨`（U+4E28）を使う。見た目も縦の一本線で崩れない。
 *
 * 純粋関数。置き換えたい文字が増えてもここだけを見ればよい。
 */
export function verticalText(text: string): string {
  return text.replace(/[-–—〜~｜]/g, '丨');
}
